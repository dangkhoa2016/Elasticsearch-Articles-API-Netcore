# ============================================================================
# Health Checks - Curl Test Commands
# ============================================================================
export BASE_URL="http://localhost:5000"

# ============================================================================
# 1. Basic health check
# ============================================================================
curl -s -X GET "$BASE_URL/api/health"

# ============================================================================
# 2. Detailed health check (database + elasticsearch)
# ============================================================================
curl -s -X GET "$BASE_URL/api/health/detailed"

# ============================================================================
# 3. Database health check only
# ============================================================================
curl -s -X GET "$BASE_URL/api/health/database"

# ============================================================================
# 4. Elasticsearch health check only
# ============================================================================
curl -s -X GET "$BASE_URL/api/health/elasticsearch"

# ============================================================================
# 5. Health check with verbose output (headers + body)
# ============================================================================
curl -v -X GET "$BASE_URL/api/health"

# ============================================================================
# 6. Health check with timing info
# ============================================================================
curl -s -o /dev/null -w "HTTP Status: %{http_code}\nTime: %{time_total}s\n" \
  -X GET "$BASE_URL/api/health/detailed"

# ============================================================================
# 7. Check response headers (security headers, correlation ID, etc.)
# ============================================================================
curl -s -I -X GET "$BASE_URL/api/health"
